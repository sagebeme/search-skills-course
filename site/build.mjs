// Builds the course site from the Markdown files one folder up.
// Run it after you change any lesson:   node site/build.mjs
//
// It writes two things:
//   1. assets/course-data.js : every lesson's Markdown, so pages work by double-clicking
//      index.html (no web server needed, because browsers won't fetch files from file://).
//   2. The lesson list and library card inside index.html, as plain HTML, so the home
//      page still shows them with JavaScript turned off.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const SITE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(SITE, '..');

// One entry per lesson file. "short" and "blurb" are for the home page cards;
// the lesson page uses the Markdown's own title.
const META = {
  '00-how-to-search-well': { short: 'How to search well', blurb: 'Pick the words the answer uses, then check who is talking.', image: 'magnifying-glass.webp', alt: 'A magnifying glass with a black handle on white paper', kind: 'photo', pos: '50% 30%' },
  '01-google-search-operators': { short: 'Google search operators', blurb: 'Quotes, minus, site: and filetype: to skip the junk.', image: 'google-advanced.webp', alt: 'Google Advanced Search, with boxes for exact phrase, none of these words, and site', kind: 'product', pos: '0% 30%' },
  '02-google-free-sources': { short: 'Free official sources', blurb: 'Reports, research papers, old web pages and raw data.', image: 'wayback.webp', alt: 'The Wayback Machine home page with its search box', kind: 'product', pos: '40% 20%' },
  '03-beyond-google': { short: 'Beyond Google', blurb: 'Other search engines, Wikipedia done right, free libraries.', image: 'marginalia.webp', alt: 'Marginalia Search, a search engine for small non-commercial websites', kind: 'product', pos: '20% 0%' },
  '04-telegram': { short: 'Telegram', blurb: 'Find real learning channels and spot the fake ones.', image: 'telegram.webp', alt: 'A public Telegram channel read in a web browser, showing subscribers and views', kind: 'product', pos: '50% 0%' },
  '05-reddit': { short: 'Reddit', blurb: 'Community wikis, honest reviews, and hidden ads.', image: 'reddit-wiki.webp', alt: 'The r/learnprogramming FAQ wiki page on Reddit', kind: 'product', pos: '60% 20%' },
  '06-spotting-scams': { short: 'Spotting scams', blurb: 'Fake course channels, poisoned downloads, phishing links.', image: 'virustotal.webp', alt: 'VirusTotal, where you can check a link or file for malware', kind: 'product', pos: '50% 10%' },
  '07-free-legal-learning': { short: 'Free, legal learning', blurb: 'Free courses, open textbooks, library apps, official docs.', image: 'openstax.webp', alt: 'OpenStax, free peer-reviewed textbooks, with sociology and physics covers', kind: 'product', pos: '100% 45%' },
  '08-final-project': { short: 'Final project', blurb: 'Build your own free plan to learn one real thing.', image: 'reading-room-seattle.webp', alt: 'A gothic university reading room with long tables and chandeliers', kind: 'photo', pos: '50% 50%' },
};

const EXTRAS = {
  about: { file: 'README.md', short: 'About this course' },
  resources: { file: 'resources.md', short: 'Resource list' },
  cheatsheet: { file: 'cheatsheet.md', short: 'Cheat sheet' },
};

const read = (p) => readFileSync(p, 'utf8').replace(/\r\n/g, '\n');
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

const files = readdirSync(join(ROOT, 'lessons')).filter((f) => f.endsWith('.md')).sort();
const lessons = files.map((f) => {
  const id = f.replace(/\.md$/, '');
  const md = read(join(ROOT, 'lessons', f));
  const meta = META[id];
  if (!meta) throw new Error(`No META entry for ${id}: add one in site/build.mjs`);
  const h1 = (/^# (.+)$/m.exec(md) || [])[1] || id;
  const title = h1.replace(/^Lesson \d+:\s*/, '');
  const time = ((/\*\*Time:\*\*\s*([^\n.]+)/.exec(md) || [])[1] || '').replace(/^about\s+/i, '').trim().replace(/\s*[\u2013\u2014]\s*/g, ' to ');
  const num = id.slice(0, 2);
  return { id, num, title, time, md, ...meta };
});

const extras = Object.fromEntries(Object.entries(EXTRAS).map(([id, e]) => {
  const md = read(join(ROOT, e.file));
  const title = ((/^# (.+)$/m.exec(md) || [])[1] || e.short);
  return [id, { id, title, short: e.short, md }];
}));

// Count the sites in the resource list (table rows that hold a link), never typed by hand.
const siteCount = (extras.resources.md.match(/^\|\s*\[[^\]]+\]\(https?:/gm) || []).length;

writeFileSync(join(SITE, 'assets', 'course-data.js'),
  '// Generated by site/build.mjs from the Markdown files. Do not edit by hand.\n' +
  `window.COURSE = ${JSON.stringify({ lessons, extras, siteCount }, null, 1)};\n`);

// ----- Static HTML for index.html -----
const tilts = [-1.6, 1.2, -0.8, 1.8, -1.2, 0.9, -1.8, 1.4, -1];
const cardRows = lessons.map((l) => `      <li><a href="lesson.html?l=${l.id}"><span class="card-no num">${l.num}</span><span class="card-title">${esc(l.short)}</span><span class="card-stamp" data-stamp="${l.id}"></span></a></li>`).join('\n');
const grid = lessons.map((l, i) => `      <li class="lesson-card" style="--tilt: ${tilts[i % tilts.length]}deg">
        <a href="lesson.html?l=${l.id}">
          <span class="shot" data-slot="lesson-${l.num}" data-kind="${l.kind}" data-alt="${esc(l.alt)}"><img src="images/${l.image}" alt="${esc(l.alt)}" loading="lazy" decoding="async" style="object-position: ${l.pos}"></span>
          <span class="lesson-card__text">
            <span class="lesson-card__head"><span class="disc num" aria-hidden="true">${l.num}</span><h3><span class="visually-hidden">Lesson ${l.num}: </span>${esc(l.short)}</h3></span>
            <span class="lesson-card__blurb">${esc(l.blurb)}</span>
            <small>${esc(l.time)}<span class="card-done" data-done="${l.id}"></span></small>
          </span>
        </a>
      </li>`).join('\n');

const indexPath = join(SITE, 'index.html');
let html = read(indexPath);
const put = (name, body) => {
  const re = new RegExp(`(<!-- build:${name} -->)[\\s\\S]*?(\\s*<!-- /build:${name} -->)`);
  if (!re.test(html)) throw new Error(`index.html is missing the build:${name} markers`);
  html = html.replace(re, `$1\n${body}$2`);
};
put('card', cardRows);
put('grid', grid);
put('count', `${lessons.length}`);
put('sites', `${siteCount}`);
writeFileSync(indexPath, html);

console.log(`built ${lessons.length} lessons, ${Object.keys(extras).length} extra pages, ${siteCount} sites in the resource list`);
